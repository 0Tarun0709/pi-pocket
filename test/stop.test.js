import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, copyFile, cp, symlink, rm, writeFile, readFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Server, request } from 'node:http';

test('all-stop aborts, discards remote queue and stays disabled until enabled locally', async () => {
  const dir = await mkdtemp(join(tmpdir(), 'pi-remote-test-'));
  await mkdir(join(dir, 'extensions/pocket'), { recursive: true });
  process.env.PI_CODING_AGENT_DIR = join(dir, 'state');
  await copyFile('extensions/pocket/index.ts', join(dir, 'extensions/pocket/index.ts'));
  await copyFile('extensions/pocket/auth.ts', join(dir, 'extensions/pocket/auth.ts'));
  await copyFile('extensions/pocket/tailscale.ts', join(dir, 'extensions/pocket/tailscale.ts'));
  await copyFile('extensions/pocket/sessions.ts', join(dir, 'extensions/pocket/sessions.ts'));
  await cp('web', join(dir, 'web'), { recursive: true });
  await symlink(resolve('node_modules'), join(dir, 'node_modules'));
  const { default: extension } = await import(pathToFileURL(join(dir, 'extensions/pocket/index.ts')));
  const events = {}, commands = {};
  let url, code, aborts = 0, sent = [], entries = [], renderer, idle = false;
  const ctx = { cwd: dir, sessionManager: { getBranch: () => [] }, isIdle: () => idle, abort: () => aborts++, ui: { notify: message => { if (message.startsWith('PockPi: http')) url = message.slice('PockPi: '.length); }, custom: async factory => { code = factory({}, { fg: (_color, text) => text }, {}, () => {}).render(200).find(line => line.startsWith('Code: ')).slice(6); } } };
  extension({ on: (name, fn) => events[name] = fn, registerCommand: (name, command) => commands[name] = command, registerEntryRenderer: (_type, fn) => renderer = fn, appendEntry: (type, data) => entries.push({ type, data }), sendUserMessage: text => sent.push(text) });
  const original = Server.prototype.listen;
  Server.prototype.listen = function (_port, host, callback) { return original.call(this, 0, host, callback); };
  try {
    await mkdir(join(dir, '.pi'));
    await writeFile(join(dir, '.pi/remote-disabled'), 'legacy lock');
    await events.session_start({}, ctx);
    assert.equal(url, undefined);
    assert.match(await readFile(join(dir, 'state/pi-pocket/remote-disabled'), 'utf8'), /disabled/);
    await commands.remote.handler('enable', ctx);
    await commands.remote.handler('pair local', ctx);
    const paired = await fetch(url + '/api/pair', { method: 'POST', headers: { origin: url, 'content-type': 'application/json' }, body: JSON.stringify({ code }) });
    assert.equal(paired.status, 200);
    const cookie = paired.headers.get('set-cookie').split(';')[0];
    const headers = () => ({ cookie });
    const get = path => fetch(url + path, { headers: headers() });
    const post = (path, body = {}) => fetch(url + path, { method: 'POST', headers: { ...headers(), origin: url, 'content-type': 'application/json' }, body: JSON.stringify(body) });
    assert.equal((await fetch(url + '/api/session')).status, 401);
    assert.equal((await fetch(url + '/api/session', { headers: { cookie: 'pi-pocket-local=wrong' } })).status, 401);
    await commands.remote.handler('share laptop.test.ts.net', ctx);
    const raw = (path, headers, method = 'GET') => new Promise((resolve, reject) => {
      const req = request(url + path, { headers, method }, res => { res.resume(); resolve(res.statusCode); });
      req.on('error', reject); req.end(method === 'POST' ? JSON.stringify({ text: 'from phone' }) : undefined);
    });
    const remoteHeaders = { cookie: cookie.replace('pi-pocket-local', '__Host-pi-pocket'), host: 'laptop.test.ts.net' };
    assert.equal(await raw('/api/session', { host: remoteHeaders.host }), 401);
    assert.equal(await raw('/api/session', remoteHeaders), 200);
    const [{ id }] = await (await get('/api/sessions')).json();
    assert.equal(await raw('/api/sessions', { host: remoteHeaders.host }), 401);
    assert.equal(await raw(`/api/sessions/${id}/session`, { host: remoteHeaders.host }), 401);
    assert.equal(await raw(`/api/sessions/${id}/session`, remoteHeaders), 200);
    assert.equal(await raw(`/api/sessions/${id}/prompt`, { ...remoteHeaders, origin: 'https://evil.test.ts.net', 'content-type': 'application/json' }, 'POST'), 403);
    assert.equal(await raw('/api/session', { ...headers(), host: 'evil.test.ts.net' }), 403);
    assert.equal(await raw('/api/stop', { ...remoteHeaders, origin: 'https://evil.test.ts.net', 'content-type': 'application/json' }, 'POST'), 403);
    assert.equal(await raw('/api/stop', { ...remoteHeaders, 'content-type': 'application/json' }, 'POST'), 403);
    assert.equal(await raw(`/api/sessions/${id}/prompt`, { ...remoteHeaders, origin: 'https://laptop.test.ts.net', 'content-type': 'application/json' }, 'POST'), 202);
    idle = true;
    await new Promise(resolve => setTimeout(resolve, 350));
    assert.deepEqual(sent, ['from phone']);
    assert.deepEqual(entries, [{ type: 'pi-pocket-prompt', data: { via: 'tailscale' } }]);
    assert.match(renderer(entries[0], {}, { fg: (_color, text) => text }).render(80)[0], /PockPi · Tailscale address/);
    assert.equal((await post('/api/prompt', { text: 'from local browser' })).status, 202);
    await new Promise(resolve => setTimeout(resolve, 350));
    assert.deepEqual(sent, ['from phone', 'from local browser']);
    assert.deepEqual(entries[1], { type: 'pi-pocket-prompt', data: { via: 'local' } });
    sent = [];
    idle = false;
    assert.equal((await post('/api/prompt', { text: 'queued' })).status, 202);
    assert.equal((await (await get('/api/session')).json()).queued, 1);
    assert.equal((await post('/api/stop')).status, 200);
    assert.equal(aborts, 1);
    assert.equal((await post('/api/stop-all')).status, 200);
    assert.equal(aborts, 2);
    idle = true;
    await new Promise(resolve => setTimeout(resolve, 350));
    assert.deepEqual(sent, []);
    assert.equal(entries.length, 2);
    await assert.rejects(fetch(url));
    await events.session_shutdown();
    await events.session_start({}, ctx);
    await assert.rejects(fetch(url));
    await commands.remote.handler('enable', ctx);
    await assert.rejects(fetch(url));
    await commands.remote.handler('pair local', ctx);
    assert.equal(await raw('/api/session', remoteHeaders), 200);
    assert.equal((await get('')).status, 200);
    assert.equal((await (await get('/api/session')).json()).queued, 0);
  } finally {
    await events.session_shutdown();
    Server.prototype.listen = original;
    await rm(dir, { recursive: true, force: true });
  }
});
